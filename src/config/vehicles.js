export const NATION_IDS = Object.freeze(['USA', 'USSR', 'GERMANY']);

export function getPlayerVehicleSpec(nationId, weaponTier) {
  const nation = NATIONS[nationId] || NATIONS.USA;
  const tierIdx = Math.max(0, Math.min(nation.tiers.length - 1, weaponTier || 0));
  return {
    nation,
    tier: tierIdx,
    ...nation.tiers[tierIdx],
  };
}

